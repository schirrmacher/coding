#!/usr/bin/env python3
"""Per-app SNI allowlist proxy and DNS forwarder.

Bind host veth IPs from the proxy config; route TLS by namespace source IP.
TLS stays end to end. DNS answers are untrusted; SNI gates TLS connections.
"""

import argparse
import asyncio
import sys
from pathlib import Path
from sandbox_proxy_core.common import HTTPS_PORT, TLS_RECORD_HEADER_SIZE, TLS_RECORD_LENGTH_OFFSET, log
from sandbox_proxy_core.config import Endpoints, load_proxy_config
from sandbox_proxy_core.tls import SniProxy, sni_from_client_hello, sni_from_extensions, sni_from_server_name_list, splice
from sandbox_proxy_core.dns import DnsForwarder, DnsUplink, handle_dns_tcp, relay_dns_tcp_query, start_dns_udp, upstream_resolvers

async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apps-json", required=True, type=Path,
                        help="proxy config generated by host/up")
    parser.add_argument("--upstream-port", type=int, default=HTTPS_PORT,
                        help="upstream TLS port; override only for testing")
    parser.add_argument("--upstream-host", default=None,
                        help="fixed upstream host; default is the SNI name (testing only)")
    args = parser.parse_args()

    apps, sni_port, dns_port = load_proxy_config(args.apps_json)
    routes = {netns_ip: endpoints for _, netns_ip, endpoints in apps}
    sni_proxy = SniProxy(routes, args.upstream_port, args.upstream_host)
    dns_resolvers = upstream_resolvers()

    # Keep UDP transports referenced for the lifetime of the listeners.
    sni_servers = [
        await asyncio.start_server(sni_proxy.handle, ip, sni_port)
        for ip, _, _ in apps
    ]
    dns_tcp_servers = [
        await asyncio.start_server(handle_dns_tcp, ip, dns_port)
        for ip, _, endpoints in apps if endpoints.entries
    ]
    dns_udp_transports = [
        await start_dns_udp(ip, dns_port, dns_resolvers)
        for ip, _, endpoints in apps if endpoints.entries
    ]

    apps_summary = ", ".join(
        f"{ip}:{endpoints.app}({len(endpoints.entries)})"
        for ip, _, endpoints in apps
    )
    startup_detail = (
        f"snip={sni_port} dnsp={dns_port} "
        f"apps={{{apps_summary}}} upstream_dns={dns_resolvers}"
    )
    log("START", startup_detail)

    async with asyncio.TaskGroup() as group:
        for server in sni_servers + dns_tcp_servers:
            group.create_task(server.serve_forever())


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        pass
